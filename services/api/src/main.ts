import { readFile } from 'node:fs/promises';
import { createPool } from './db.js';
import { createApp } from './app.js';
import { startMockWorker } from './outbox.js';
import { MockTransport } from './transport.js';
const secret=async(name:string)=>{const path=process.env[`${name}_FILE`];if(!path)throw new Error(`MISSING_${name}_FILE`);return (await readFile(path,'utf8')).trim();};
if(process.env.WHATSAPP_SENDING_ENABLED==='true')throw new Error('LIVE_SENDING_NOT_IMPLEMENTED_OR_AUTHORIZED');
const host=process.env.TASKPILOT_BIND_HOST??'127.0.0.1';
if(!['127.0.0.1','::1'].includes(host))throw new Error('LOOPBACK_REQUIRED_FOR_PILOT');
const pool=createPool(process.env.DATABASE_URL??'');
const app=await createApp(pool,{apiToken:await secret('TASKPILOT_API_TOKEN'),reauthSecret:await secret('TASKPILOT_REAUTH_SECRET'),encryptionKey:await secret('TASKPILOT_ENCRYPTION_KEY'),mockEnabled:process.env.TASKPILOT_MOCK_ENABLED==='true'});
const stop=await startMockWorker(pool,new MockTransport());
await app.listen({host,port:Number(process.env.TASKPILOT_BIND_PORT??8240)});
for(const signal of ['SIGINT','SIGTERM'])process.once(signal,async()=>{await app.close();await stop();await pool.end();process.exit(0);});
